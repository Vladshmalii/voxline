"""Country -> representative IANA timezone lookup.

VOAD-33: a call's calling-hours window is evaluated on the client's local
time, derived automatically from :attr:`Client.country` rather than picked by
hand. This module is the derivation step only — it takes whatever string an
upload or CRM handed us and, when it can, returns one IANA zone name for it.
When it cannot (missing, free text, an unrecognized code), the caller is
expected to fall back to the campaign's own configured timezone unchanged;
that fallback lives in the dispatcher, not here.

Mirrors ``utils.script``'s isolation rule: no project imports, stdlib only,
so this stays trivially unit-testable and reusable without pulling in
settings, the ORM, or anything else.

The mapping is deliberately a *representative* zone per country, the same
simplification every lightweight country/timezone table makes — good enough
to decide "is it daytime for this lead", not a full administrative-division
timezone database. Countries that span multiple zones (the US, Russia,
Australia, ...) get their most populous/capital zone.
"""

