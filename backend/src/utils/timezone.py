def country_to_timezone(country: str | None) -> str | None:
    """The representative IANA zone for ``country``, or None when unresolvable.

    Accepts an ISO-3166-1 alpha-2 code (case-insensitive) directly, or a
    handful of common alpha-3 codes and English country names via
    :data:`_ALIASES`. Anything else — free text we don't recognize, garbage,
    an empty string, ``None`` — returns None so the caller can fall back to
    its own configured timezone.

    Args:
        country: Whatever ``Client.country`` holds.

    Returns:
        An IANA zone name, or None when ``country`` isn't recognized.
    """
    if not country:
        return None
    key = country.strip().upper()
    if not key:
        return None
    key = _ALIASES.get(key, key)
    return COUNTRY_TIMEZONES.get(key)


def to_utc_naive(value: datetime | None) -> datetime | None:
    """``value`` as the naive UTC the database columns store.

    An explicit offset is converted; a naive value is already taken to be UTC
    and passes through, as does None.
    """
    if value is None or value.tzinfo is None:
        return value
    return value.astimezone(UTC).replace(tzinfo=None)
